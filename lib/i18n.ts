export type TranslationKeys = typeof translations.fr;

const STORAGE_KEY = "thebox_language";

/**
 * Reads stored language preference safely from localStorage.
 */
export function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "fr";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "fr") return saved;
  } catch (e) {
    console.error("Failed to read language from localStorage:", e);
  }
  return "fr";
}

/**
 * Persists language preference to localStorage and updates HTML attribute and document title.
 */
export function setStoredLanguage(lang: Language): void {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.title = translations[lang].appTitle;
    window.dispatchEvent(new CustomEvent("thebox_language_change", { detail: { language: lang } }));
  } catch (e) {
    console.error("Failed to save language to localStorage:", e);
  }
}
